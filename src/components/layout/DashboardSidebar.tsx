'use client';

import Link from 'next/link';
import { usePathname, useRouter } from 'next/navigation';
import { createClient } from '@/lib/supabase/client';
import type { User } from '@/types';

interface Props {
  user: User | null;
}

export default function DashboardSidebar({ user }: Props) {
  const pathname = usePathname();
  const router = useRouter();

  const navItems = [
    { href: '/dashboard', label: 'Главная', icon: HouseIcon },
    { href: '/assessments', label: 'Тесты', icon: ClipboardIcon },
    { href: '/dashboard/results', label: 'Мои результаты', icon: ChartIcon },
    { href: '/dashboard/plan', label: 'План развития', icon: TargetIcon },
    { href: '/profile', label: 'Профиль', icon: UserIcon },
  ];

  const hrItems = [
    { href: '/admin', label: 'Управление', icon: SettingsIcon },
    { href: '/admin/users', label: 'Пользователи', icon: UsersIcon },
    { href: '/admin/reports', label: 'Отчёты', icon: TrendingIcon },
  ];

  const handleLogout = async () => {
    const supabase = createClient();
    await supabase.auth.signOut();
    router.push('/');
  };

  const isActive = (href: string) =>
    href === '/dashboard' ? pathname === href : pathname.startsWith(href);

  const initials = user?.full_name
    ?.split(' ')
    .map((n) => n[0])
    .slice(0, 2)
    .join('')
    .toUpperCase() || '?';

  return (
    <aside className="w-60 bg-white border-r border-gray-100 flex flex-col min-h-screen">
      {/* Logo */}
      <div className="px-5 py-4 border-b border-gray-100">
        <Link href="/" className="flex items-center gap-2.5">
          <div className="w-7 h-7 rounded-lg bg-gradient-to-br from-primary-500 to-violet-600 flex items-center justify-center text-white font-bold text-xs shadow-sm shadow-primary-500/30">S</div>
          <span className="font-semibold text-gray-900 text-sm">SoftSkills Pro</span>
        </Link>
      </div>

      {/* User card */}
      {user && (
        <div className="px-4 py-3 border-b border-gray-100">
          <div className="flex items-center gap-3 p-2.5 rounded-xl bg-gray-50">
            <div className="w-8 h-8 rounded-lg bg-gradient-to-br from-primary-500 to-violet-600 flex items-center justify-center text-white font-semibold text-xs shrink-0">
              {initials}
            </div>
            <div className="min-w-0">
              <div className="text-xs font-semibold text-gray-900 truncate">{user.full_name}</div>
              <div className="text-xs text-gray-400 mt-0.5">{getRoleLabel(user.role)}</div>
            </div>
          </div>
        </div>
      )}

      {/* Navigation */}
      <nav className="flex-1 p-3 space-y-0.5">
        <p className="text-[10px] font-semibold text-gray-400 uppercase tracking-widest px-3 py-2">Меню</p>
        {navItems.map((item) => {
          const active = isActive(item.href);
          return (
            <Link
              key={item.href}
              href={item.href}
              className={`flex items-center gap-2.5 px-3 py-2 rounded-lg text-sm transition-all ${
                active
                  ? 'bg-primary-50 text-primary-700 font-medium'
                  : 'text-gray-500 hover:bg-gray-50 hover:text-gray-900'
              }`}
            >
              <item.icon
                className={`w-4 h-4 shrink-0 ${active ? 'text-primary-600' : 'text-gray-400'}`}
              />
              {item.label}
              {active && (
                <span className="ml-auto w-1.5 h-1.5 rounded-full bg-primary-500" />
              )}
            </Link>
          );
        })}

        {(user?.role === 'hr' || user?.role === 'admin') && (
          <>
            <p className="text-[10px] font-semibold text-gray-400 uppercase tracking-widest px-3 py-2 mt-3">HR-панель</p>
            {hrItems.map((item) => {
              const active = isActive(item.href);
              return (
                <Link
                  key={item.href}
                  href={item.href}
                  className={`flex items-center gap-2.5 px-3 py-2 rounded-lg text-sm transition-all ${
                    active
                      ? 'bg-primary-50 text-primary-700 font-medium'
                      : 'text-gray-500 hover:bg-gray-50 hover:text-gray-900'
                  }`}
                >
                  <item.icon
                    className={`w-4 h-4 shrink-0 ${active ? 'text-primary-600' : 'text-gray-400'}`}
                  />
                  {item.label}
                  {active && (
                    <span className="ml-auto w-1.5 h-1.5 rounded-full bg-primary-500" />
                  )}
                </Link>
              );
            })}
          </>
        )}
      </nav>

      {/* Logout */}
      <div className="p-3 border-t border-gray-100">
        <button
          onClick={handleLogout}
          className="w-full flex items-center gap-2.5 px-3 py-2 rounded-lg text-sm text-gray-400 hover:bg-gray-50 hover:text-gray-700 transition-all"
        >
          <LogoutIcon className="w-4 h-4 shrink-0" />
          Выйти
        </button>
      </div>
    </aside>
  );
}

function getRoleLabel(role: string): string {
  const labels: Record<string, string> = {
    admin: 'Администратор',
    hr: 'HR-менеджер',
    manager: 'Руководитель',
    employee: 'Сотрудник',
    candidate: 'Кандидат',
  };
  return labels[role] || role;
}

